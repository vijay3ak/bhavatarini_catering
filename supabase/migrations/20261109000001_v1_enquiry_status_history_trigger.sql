-- -----------------------------------------------------------------------------
-- SECTION 1: Anti-Forgery & Privilege Hardening on History Table
-- -----------------------------------------------------------------------------
-- Revoke direct table-level INSERT privileges from authenticated browser clients.
-- History rows must ONLY be generated by the database trigger engine.
REVOKE INSERT ON TABLE public.enquiry_status_history FROM authenticated;

-- Drop obsolete client INSERT policy (trigger writes under postgres owner privileges)
DROP POLICY IF EXISTS "history_insert_active_admin" ON public.enquiry_status_history;

-- -----------------------------------------------------------------------------
-- SECTION 2: Hardened Atomic Trigger Function
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.log_enquiry_status_change()
RETURNS TRIGGER AS $$
DECLARE
  v_actor_id uuid;
BEGIN
  -- Extract authenticated administrator UUID from PostgREST JWT session
  v_actor_id := auth.uid();

  -- Strict identity enforcement:
  -- In V1, enquiry stage transitions represent administrative decisions and
  -- must be attributed to an active administrator. Unauthenticated and service-role
  -- updates lacking an administrator session context fail closed.
  IF v_actor_id IS NULL THEN
    RAISE EXCEPTION 'Enquiry status transitions require an authenticated administrator session.';
  END IF;

  -- Atomic history insertion within the active PostgreSQL transaction
  INSERT INTO public.enquiry_status_history (
    enquiry_id,
    old_status,
    new_status,
    changed_by,
    reason,
    created_at
  ) VALUES (
    NEW.id,
    OLD.status,
    NEW.status,
    v_actor_id,
    NULL, -- Retain NULL for standard UI coordinator transitions; never copy customer details
    pg_catalog.now()
  );

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, pg_temp;

-- -----------------------------------------------------------------------------
-- SECTION 3: Function Ownership & Execution Restriction
-- -----------------------------------------------------------------------------
-- Ensure the function is owned by postgres (database superuser/schema owner)
ALTER FUNCTION public.log_enquiry_status_change() OWNER TO postgres;

-- Revoke default PUBLIC execute privileges.
-- Trigger functions must NOT be callable directly via PostgREST RPC (/rpc/...)
REVOKE ALL ON FUNCTION public.log_enquiry_status_change() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.log_enquiry_status_change() FROM anon, authenticated;

-- -----------------------------------------------------------------------------
-- SECTION 4: Bind Trigger to public.enquiries
-- -----------------------------------------------------------------------------
DROP TRIGGER IF EXISTS trg_log_enquiry_status_change ON public.enquiries;

CREATE TRIGGER trg_log_enquiry_status_change
  AFTER UPDATE OF status ON public.enquiries
  FOR EACH ROW
  WHEN (OLD.status IS DISTINCT FROM NEW.status)
  EXECUTE FUNCTION public.log_enquiry_status_change();
